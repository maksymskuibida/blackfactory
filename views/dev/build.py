#!/usr/bin/env python3
"""Write the design tokens into the page template, so each value lives in one place.

    python3 views/dev/build.py            rewrite the token block in views/templates/page.html
    python3 views/dev/build.py --check    exit 1 if the template is out of date (for CI)
    python3 views/dev/build.py --css FILE write tokens + component styles as one stylesheet (for the design system)

Source of values: views/tokens/tokens.json. Standard library only.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TOKENS = ROOT / "tokens" / "tokens.json"
TEMPLATE = ROOT / "templates" / "page.html"

BEGIN, END = "/*TOKENS:BEGIN*/", "/*TOKENS:END*/"
C_BEGIN, C_END = "/*COMPONENTS:BEGIN*/", "/*COMPONENTS:END*/"


def decls(d, indent="  "):
    items = [f"--{k}: {v};" for k, v in d.items()]
    lines, cur = [], indent
    for it in items:
        if len(cur) + len(it) + 1 > 118 and cur.strip():
            lines.append(cur.rstrip())
            cur = indent
        cur += it + " "
    if cur.strip():
        lines.append(cur.rstrip())
    return "\n".join(lines)


def tokens_css(t):
    light = {**t["shared"], **t["light"], **t["aliases"]}
    dark = t["dark"]
    out = [
        "/* generated by views/dev/build.py from views/tokens/tokens.json: do not edit here */",
        ":root {",
        decls(light),
        "}",
        "@media (prefers-color-scheme: dark) { :root:not([data-theme=\"light\"]) {",
        decls(dark),
        "  color-scheme: dark } }",
        ":root[data-theme=\"dark\"] {",
        decls(dark),
        "  color-scheme: dark }",
    ]
    return "\n".join(out)


def between(text, a, b):
    i, j = text.index(a) + len(a), text.index(b)
    return text[i:j]


def components_css(text):
    return between(text, C_BEGIN, C_END).strip("\n")


def build():
    t = json.loads(TOKENS.read_text())
    text = TEMPLATE.read_text()
    new = re.sub(
        re.escape(BEGIN) + r".*?" + re.escape(END),
        lambda m: BEGIN + "\n" + tokens_css(t) + "\n" + END,
        text,
        flags=re.S,
    )
    return t, text, new


def main(argv):
    t, text, new = build()
    if "--check" in argv:
        if new != text:
            print("views/templates/page.html is out of date: run python3 views/dev/build.py")
            return 1
        print("template is up to date")
        return 0
    if "--css" in argv:
        dest = Path(argv[argv.index("--css") + 1])
        dest.write_text(tokens_css(t) + "\n\n" + components_css(new) + "\n")
        print(f"wrote {dest}")
        return 0
    if new != text:
        TEMPLATE.write_text(new)
        print("updated", TEMPLATE.relative_to(ROOT.parent))
    else:
        print("template already up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
