#!/usr/bin/env python3
"""Write the design tokens into the page template, so each value lives in one place.

    python3 views/dev/build.py            rewrite the token block in views/templates/page.html and write
                                          harness/claude/panel/src/tokens.ts for the desktop panel
    python3 views/dev/build.py --check    exit 1 if the template or the panel's tokens are out of date (for CI)
    python3 views/dev/build.py --css FILE write tokens + component styles as one stylesheet other tools can import

Source of values: views/tokens/tokens.json. Standard library only.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TOKENS = ROOT / "tokens" / "tokens.json"
TEMPLATE = ROOT / "templates" / "page.html"

BEGIN, END = "/*TOKENS:BEGIN*/", "/*TOKENS:END*/"
C_BEGIN, C_END = "/*COMPONENTS:BEGIN*/", "/*COMPONENTS:END*/"


def decls(d, indent="  "):
    items = [f"--{k}: {v};" for k, v in d.items()]
    lines, cur = [], indent
    for it in items:
        if len(cur) + len(it) + 1 > 118 and cur.strip():
            lines.append(cur.rstrip())
            cur = indent
        cur += it + " "
    if cur.strip():
        lines.append(cur.rstrip())
    return "\n".join(lines)


def tokens_css(t):
    light = {**t["shared"], **t["light"], **t["aliases"]}
    dark = t["dark"]
    out = [
        "/* generated by views/dev/build.py from views/tokens/tokens.json: do not edit here */",
        ":root {",
        decls(light),
        "}",
        "@media (prefers-color-scheme: dark) { :root:not([data-theme=\"light\"]) {",
        decls(dark),
        "  color-scheme: dark } }",
        ":root[data-theme=\"dark\"] {",
        decls(dark),
        "  color-scheme: dark }",
    ]
    return "\n".join(out)


PANEL_TOKENS = ROOT.parent / "harness" / "claude" / "panel" / "src" / "tokens.ts"

# The tones of tags: which token names make the background, the text and the dot of each.
TONES = {
    "ok": ("ok-bg", "ok-fg", "ok-fg"),
    "info": ("accent-soft", "accent", "accent"),
    "warn": ("warn-bg", "warn-fg", "warn-dot"),
    "crit": ("crit-bg", "crit-fg", "crit-fg"),
    "neutral": ("low-bg", "low-fg", "control"),
}


def px(v):
    return int(str(v).removesuffix("px"))


def panel_tokens(t):
    """The desktop panel's copy of the tokens, as one TypeScript module."""
    sh = t["shared"]
    data = {
        "version": t["version"],
        "light": {**t["light"]},
        "dark": {**t["dark"]},
        "type": {k[3:]: px(v) for k, v in sh.items() if k.startswith("fs-")},
        "space": {k[3:]: px(v) for k, v in sh.items() if k.startswith("sp-")},
        "radius": {k[2:]: px(v) for k, v in sh.items() if k.startswith("r-")},
        "fonts": {"body": sh["body"], "mono": sh["mono"]},
        "tones": {
            name: {
                theme: {"bg": t[theme][bg], "fg": t[theme][fg], "dot": t[theme][dot]}
                for theme in ("light", "dark")
            }
            for name, (bg, fg, dot) in TONES.items()
        },
    }
    body = json.dumps(data, indent=2, ensure_ascii=False)
    return (
        "// generated by views/dev/build.py from views/tokens/tokens.json: do not edit here\n"
        f"export const tokens = {body} as const\n"
        "\nexport type ToneName = keyof typeof tokens.tones\n"
    )


def between(text, a, b):
    i, j = text.index(a) + len(a), text.index(b)
    return text[i:j]


def components_css(text):
    return between(text, C_BEGIN, C_END).strip("\n")


def build():
    t = json.loads(TOKENS.read_text(encoding="utf-8"))
    text = TEMPLATE.read_text(encoding="utf-8")
    new = re.sub(
        re.escape(BEGIN) + r".*?" + re.escape(END),
        lambda m: BEGIN + "\n" + tokens_css(t) + "\n" + END,
        text,
        flags=re.S,
    )
    return t, text, new


def main(argv):
    t, text, new = build()
    panel_new = panel_tokens(t)
    panel_old = PANEL_TOKENS.read_text(encoding="utf-8") if PANEL_TOKENS.exists() else ""
    if "--check" in argv:
        bad = False
        if new != text:
            print("views/templates/page.html is out of date: run python3 views/dev/build.py")
            bad = True
        if panel_new != panel_old:
            print("harness/claude/panel/src/tokens.ts is out of date: run python3 views/dev/build.py")
            bad = True
        if bad:
            return 1
        print("template and panel tokens are up to date")
        return 0
    if "--css" in argv:
        dest = Path(argv[argv.index("--css") + 1])
        dest.write_text(tokens_css(t) + "\n\n" + components_css(new) + "\n", encoding="utf-8")
        print(f"wrote {dest}")
        return 0
    if new != text:
        TEMPLATE.write_text(new, encoding="utf-8")
        print("updated", TEMPLATE.relative_to(ROOT.parent))
    else:
        print("template already up to date")
    if panel_new != panel_old:
        PANEL_TOKENS.parent.mkdir(parents=True, exist_ok=True)
        PANEL_TOKENS.write_text(panel_new, encoding="utf-8")
        print("updated", PANEL_TOKENS.relative_to(ROOT.parent))
    else:
        print("panel tokens already up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
